def generate_playbook_markdown(playbook: Dict) -> str:
    """
    Generate Markdown report for a visibility playbook.
    """
    domain = playbook.get("domain", "")
    intent = playbook.get("intent", "")
    fixes = playbook.get("fixes", [])

    md = [
        f"# Visibility Playbook — {domain}",
        f"**Intent:** {intent}",
        "",
        "## TL;DR",
        "```html",
        (playbook.get("tldr_html") or "").strip(),
        "```",
        "",
        "## FAQ",
        "```html",
        (playbook.get("faq_html") or "").strip(),
        "```",
        "",
        "## Organization JSON-LD",
        "```json",
        __import__("json").dumps(playbook.get("jsonld", {}), indent=2),
        "```",
        "",
        "## Fixes",
    ]
    for fix in fixes:
        md.extend(
            [
                f"### {fix.get('title')}",
                f"Why: {fix.get('why', '')}",
                "```" + (fix.get("language") or ""),
                (fix.get("snippet") or "").strip(),
                "```",
                "",
            ]
        )

    md.extend(
        [
            "## Acceptance Tests",
            "```python",
            (playbook.get("acceptance_tests_py") or "").strip(),
            "```",
        ]
    )

    return "\n".join(md)


def generate_playbook_docx(playbook: Dict) -> bytes:
    """
    Generate DOCX document for a visibility playbook.
    """
    domain = playbook.get("domain", "")
    intent = playbook.get("intent", "")
    fixes = playbook.get("fixes", [])

    doc = Document()
    doc.add_heading("Visibility Playbook", 0)
    doc.add_paragraph(f"Domain: {domain}")
    doc.add_paragraph(f"Intent: {intent}")

    # TL;DR
    doc.add_heading("TL;DR", 1)
    doc.add_paragraph(playbook.get("tldr_html") or "")

    # FAQ
    doc.add_heading("FAQ", 1)
    doc.add_paragraph(playbook.get("faq_html") or "")

    # JSON-LD
    doc.add_heading("Organization JSON-LD", 1)
    doc.add_paragraph(__import__("json").dumps(playbook.get("jsonld", {}), indent=2))

    # Fixes
    doc.add_heading("Fixes", 1)
    for fix in fixes:
        doc.add_heading(fix.get("title") or "Fix", 2)
        doc.add_paragraph(f"Why: {fix.get('why', '')}")
        snippet = fix.get("snippet") or ""
        doc.add_paragraph(snippet)

    # Acceptance tests
    doc.add_heading("Acceptance Tests", 1)
    doc.add_paragraph(playbook.get("acceptance_tests_py") or "")

    bio = BytesIO()
    doc.save(bio)
    bio.seek(0)
    return bio.getvalue()
